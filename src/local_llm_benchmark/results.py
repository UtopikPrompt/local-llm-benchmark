"""Result serialization utilities for benchmark data.

This module provides dataclasses and serialization functions for converting
benchmark results to dictionaries and various output formats (CSV, JSON).
"""

import csv
import json
from pathlib import Path
from typing import Any

__all__ = ["Row", "CSV_COLUMNS", "write_csv", "write_json", "write_report"]


class Row:
    """A row representing a single benchmark execution result.

    This dataclass encapsulates all fields required to represent a complete
    benchmark test result, including performance metrics and quality assessment.

    Attributes:
        engine (str): The name of the benchmark engine used (e.g., "ollama", "llama.cpp").
        model (str): The identifier for the model being tested (e.g., "gemma4:e2b").
        judge (str): The name of the quality judge used, defaults to empty string.
        task_id (str): The unique identifier for the benchmark task (e.g., "qa").
        category (str): The category of the benchmark task (e.g., "qa").
        prompt (str): The prompt text used for the benchmark.
        expected (str): The expected output for the task.
        output (str): The actual output generated by the model.
        ttft_s (float): Time to first token in seconds.
        tok_per_s (float): Tokens per second throughput.
        iters_per_s (float): Iterations per second throughput.
        quality_passed (bool): Whether the output quality passed the threshold.
        quality_deterministic (bool): Whether the output was deterministic.
        quality_judge (bool): Whether a quality judge was used.
        quality_note (str): Additional notes about the quality assessment.

    Example:
        >>> row = Row(
        ...     engine="ollama",
        ...     model="gemma4:e2b",
        ...     prompt="What is 2+2?",
        ...     expected="4",
        ...     output="4",
        ...     ttft_s=0.1,
        ...     tok_per_s=10.0,
        ...     iters_per_s=100.0,
        ...     quality_passed=True,
        ... )
        >>> row.to_dict()
        {'engine': 'ollama', 'model': 'gemma4:e2b', 'prompt': 'What is 2+2?', ...}
    """

    engine: str = ""
    model: str = ""
    judge: str = ""
    task_id: str = ""
    category: str = "qa"
    prompt: str = ""
    expected: str = ""
    output: str = ""
    ttft_s: float = 0.0
    tok_per_s: float = 0.0
    iters_per_s: float = 0.0
    quality_passed: bool = False
    quality_deterministic: bool = False
    quality_judge: bool = False
    quality_note: str = ""

    def to_dict(self) -> dict[str, Any]:
        """Convert the row to a dictionary representation.

        Returns:
            A dictionary containing all row fields with their current values.

        Example:
            >>> row = Row(engine="ollama", model="llama3", prompt="test")
            >>> d = row.to_dict()
            >>> "engine" in d
            True
        """
        return dict(self.__dict__)

    def __repr__(self) -> str:
        """Return a string representation of the row.

        Returns:
            A string showing the engine and model fields.
        """
        return f"Row(engine='{self.engine}', model='{self.model}')"


# Define the order of columns for CSV output
CSV_COLUMNS: tuple[str, ...] = (
    "engine",
    "model",
    "judge",
    "task_id",
    "category",
    "prompt",
    "expected",
    "output",
    "ttft_s",
    "tok_per_s",
    "iters_per_s",
    "quality_passed",
    "quality_deterministic",
    "quality_judge",
    "quality_note",
)


def write_csv(rows: list[Row], output_path: Path) -> None:
    """Write benchmark rows to a CSV file.

        Args:
            rows: A list of Row instances to serialize.
            output_path: The file path where the CSV will be written.

        Example:
            >>> rows = [Row(engine="ollama", model="llama3", prompt="test")]
            >>> write_csv(rows, "benchmarks.csv")
        """
    with output_path.open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=CSV_COLUMNS, extrasaction="ignore")
        writer.writeheader()
        for row in rows:
            writer.writerow(row.to_dict())


def write_json(rows: list[Row], output_path: Path) -> None:
    """Write benchmark rows to a JSON file.

        Args:
            rows: A list of Row instances to serialize.
            output_path: The file path where the JSON will be written.

        Example:
            >>> rows = [Row(engine="ollama", model="llama3", prompt="test")]
            >>> write_json(rows, "benchmarks.json")
        """
    with output_path.open("w", encoding="utf-8") as f:
        json.dump([row.to_dict() for row in rows], f, indent=2)


def write_report(rows: list[Row], output_path: Path, fmt: str = "json") -> None:
    """Write benchmark rows to a report file in the specified format.

        This is a dispatcher function that routes to the appropriate
        serialization function based on the format specified.

        Args:
            rows: A list of Row instances to serialize.
            output_path: The file path where the report will be written.
            fmt: The output format, either "json" or "csv". Defaults to "json".

        Raises:
            ValueError: If an unsupported format is specified.

        Example:
            >>> rows = [Row(engine="ollama", model="llama3", prompt="test")]
            >>> write_report(rows, "report.json", fmt="json")
            >>> write_report(rows, "report.csv", fmt="csv")
        """
    if fmt.lower() == "json":
        write_json(rows, output_path)
    elif fmt.lower() == "csv":
        write_csv(rows, output_path)
    else:
        raise ValueError(f"Unsupported format: {fmt!r}. Use 'json' or 'csv'.")


