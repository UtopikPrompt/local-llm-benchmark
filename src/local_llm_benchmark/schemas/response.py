"""Response schemas for LLM interactions.

These dataclasses define the structure of responses from LLM engines,
including completion results and error information.
"""

from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional


@dataclass
class LLMResponse:
    """Response from an LLM engine.
    
    This structure encapsulates the complete response from an LLM,
    including the generated content, token usage, and metadata.
    
    Attributes:
        id: Unique response identifier
        model: The model that generated the response
        choices: List of choice objects containing the generated content
        usage: Token usage statistics (prompt, completion, total)
        system_fingerprint: Fingerprint for model registry (optional)
        created: Timestamp of response creation
    """
    id: Optional[str] = field(default=None, metadata={"description": "Response ID"})
    model: Optional[str] = field(default=None, metadata={"description": "Model identifier"})
    choices: List[Dict[str, Any]] = field(default_factory=list, metadata={"description": "Generated choices"})
    usage: Optional[Dict[str, int]] = field(default=None, metadata={"description": "Token usage"})
    system_fingerprint: Optional[str] = field(default=None, metadata={"description": "Model fingerprint"})
    created: Optional[int] = field(default=None, metadata={"description": "Creation timestamp"})


@dataclass
class Choice:
    """A single choice in the response.
    
    Represents one possible completion from the LLM.
    
    Attributes:
        index: The index of this choice
        message: The message content generated by the model
        finish_reason: The reason generation ended
        logprobs: Log probability information (optional)
    """
    index: int = field(default=0, metadata={"description": "Choice index"})
    message: Optional[str] = field(default=None, metadata={"description": "Generated message"})
    finish_reason: Optional[str] = field(default=None, metadata={"description": "Generation end reason"})
    logprobs: Optional[Dict[str, Any]] = field(default=None, metadata={"description": "Log probability data"})


@dataclass
class BenchmarkResultsResponse:
    """Response containing benchmark results for a specific benchmark.
    
    Represents the aggregated results of running a benchmark against
    one or more engines, including metrics, rankings, and statistics.
    
    Attributes:
        name: The name/identifier of the benchmark
        results: List of detailed results for each engine
        summary: High-level summary of benchmark performance
        metrics: Aggregated metrics across all engines
        timestamps: When the benchmark was run
    """
    name: str = field(metadata={"description": "Benchmark name"})
    results: List[Dict[str, Any]] = field(
        default_factory=list,
        metadata={"description": "Detailed results per engine"},
    )
    summary: Optional[Dict[str, Any]] = field(
        default=None,
        metadata={"description": "Benchmark summary"},
    )
    metrics: Optional[Dict[str, Any]] = field(
        default=None,
        metadata={"description": "Aggregated metrics"},
    )
    timestamps: Optional[Dict[str, Any]] = field(
        default=None,
        metadata={"description": "Benchmark timestamps"},
    )
